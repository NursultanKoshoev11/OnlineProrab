package phone

import "testing"

func TestNormalizeProducesOneCanonicalForm(t *testing.T) {
	for input, want := range map[string]string{
		"+996700000000":      "+996700000000",
		"996700000000":       "+996700000000",
		" +996 700 000 000 ": "+996700000000",
		"+996-700-000-000":   "+996700000000",
		"(996) 700.000.000":  "+996700000000",
		"996 700000000":      "+996700000000",
		"0700000000":         "+996700000000",
		"0700 000 000":       "+996700000000",
		"(0700) 00-00-00":    "+996700000000",
		"+0700000000":        "+996700000000",
		"00996700000000":     "+996700000000",
		"00 996 700 000 000": "+996700000000",
		"+00996700000000":    "+996700000000",
		"0012025550123":      "+12025550123",
		"070000000":          "+070000000",
		"":                   "",
		"+":                  "+",
		"++996700000000":     "++996700000000",
		"99670000000a":       "99670000000a",
	} {
		if got := Normalize(input); got != want {
			t.Errorf("Normalize(%q) = %q, want %q", input, got, want)
		}
	}
}
