package httpapi

import "net/http"

func registerAPIRoutes(mux *http.ServeMux) {
	api := "/api/v1"
	mux.HandleFunc(api+"/projects", requireSubscribed(Projects))
	mux.HandleFunc(api+"/realtime", requireSubscribed(RealtimeEvents))
	mux.HandleFunc(api+"/push-tokens", requireAuth(PushTokens))
	mux.HandleFunc(api+"/projects/create-with-cover", requireSubscribed(CreateProjectWithCover))
	mux.HandleFunc(api+"/projects/", requireSubscribed(Projects))
	mux.HandleFunc(api+"/project-members", requireSubscribed(ProjectMembers))
	mux.HandleFunc(api+"/project-members/", requireSubscribed(ProjectMember))
	mux.HandleFunc(api+"/project-invites", requireSubscribed(CreateProjectInvite))
	mux.HandleFunc(api+"/project-invites/accept", requireSubscribed(AcceptProjectInvite))
	mux.HandleFunc(api+"/cost-items", requireSubscribed(withProjectMutationRBAC(CostItems, "", nil)))
	mux.HandleFunc(api+"/cost-items/", requireSubscribed(withProjectMutationRBAC(CostItems, api+"/cost-items/", costItemProjectID)))
	mux.HandleFunc(api+"/expense-ai/search", requireSubscribed(ExpenseAISearch))
	mux.HandleFunc(api+"/daily-reports", requireSubscribed(withProjectMutationRBAC(DailyReports, "", nil)))
	mux.HandleFunc(api+"/daily-reports/", requireSubscribed(withProjectMutationRBAC(DailyReports, api+"/daily-reports/", dailyReportProjectID)))
	mux.HandleFunc(api+"/files", requireSubscribed(withProjectMutationRBAC(Files, "", nil)))
	mux.HandleFunc(api+"/files/upload", requireSubscribed(UploadFile))
	mux.HandleFunc(api+"/files/download", requireSubscribed(DownloadFile))
	mux.HandleFunc(api+"/files/", requireSubscribed(withProjectMutationRBAC(Files, api+"/files/", fileProjectID)))
	mux.HandleFunc(api+"/tasks", requireSubscribed(withProjectMutationRBAC(Tasks, "", nil)))
	mux.HandleFunc(api+"/tasks/", requireSubscribed(withProjectMutationRBAC(Tasks, api+"/tasks/", taskProjectID)))
	mux.HandleFunc(api+"/audit-logs", requireSubscribed(AuditLogs))
	mux.HandleFunc(api+"/support/channels", requireSubscribed(SupportChannels))
	mux.HandleFunc(api+"/support/tickets", requireSubscribed(SupportTickets))
	mux.HandleFunc(api+"/auth/sms/request", withSMSRequestRateLimit(RequestSMSCode))
	mux.HandleFunc(api+"/auth/sms/verify", withSMSVerifyRateLimit(VerifySMSCode))
	mux.HandleFunc(api+"/account/deletion/verify", withSMSVerifyRateLimit(VerifyAccountDeletionSMSCode))
	mux.HandleFunc(api+"/auth/session", requireAuth(CreateSession))
	mux.HandleFunc(api+"/auth/session/refresh", RefreshSession)
	mux.HandleFunc(api+"/auth/session/logout", LogoutSession)
	mux.HandleFunc(api+"/account", requireAccountDeletionAuth(DeleteAccount))
	mux.HandleFunc(api+"/subscriptions/plans", optionalAuth(ListPlans))
	mux.HandleFunc(api+"/subscriptions/status", requireAuth(SubscriptionStatus))
	mux.HandleFunc(api+"/subscriptions/checkout", requireAuth(SubscriptionCheckout))
	mux.HandleFunc(api+"/payments/obank/result", OBankResult)
}
