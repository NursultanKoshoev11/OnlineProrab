func TestRequestSMSCodeFailsClosedWhenStagingSMSDeliveryIsUnavailable(t *testing.T) {
	db := openSMSAuthTestDB(t)
	oldState := appState
	defer func() { appState = oldState }()
	appState = State{
		DB:                db,
		JWTSecret:         "staging-test-signing-key-1234567890",
		AccessTokenTTL:    time.Hour,
		IsProductionLike:  true,
		IsDevelopment:     false,
		DevSMSCodeEnabled: true, // Simulate a hostile environment override.
	}

	req := httptest.NewRequest(http.MethodPost, "/api/v1/auth/sms/request", strings.NewReader(`{"phone":"+996700000001"}`))
	rec := httptest.NewRecorder()
	RequestSMSCode(rec, req)

	if rec.Code != http.StatusServiceUnavailable {
		t.Fatalf("expected status %d when staging has no SMS sender, got %d: %s", http.StatusServiceUnavailable, rec.Code, rec.Body.String())
	}
	if strings.Contains(rec.Body.String(), "dev_code") || strings.Contains(rec.Body.String(), developmentSMSCode) {
		t.Fatalf("staging response exposed a development code: %s", rec.Body.String())
	}

	var storedCodes int
	if err := db.Pool.QueryRow(context.Background(), `SELECT COUNT(*) FROM sms_login_codes`).Scan(&storedCodes); err != nil {
		t.Fatalf("count stored SMS codes: %v", err)
	}
	if storedCodes != 0 {
		t.Fatalf("expected no unusable SMS code to remain in the database, got %d", storedCodes)
	}
}

func openSMSAuthTestDB(t *testing.T) *database.DB {
	t.Helper()
	url := os.Getenv("TEST_DATABASE_URL")
	if url == "" {
		t.Skip("TEST_DATABASE_URL is not configured")
	}

	ctx, cancel := context.WithTimeout(context.Background(), 10*time.Second)
	defer cancel()
	adminDB, err := database.Open(ctx, url)
	if err != nil {
		t.Fatalf("open auth test database: %v", err)
	}
	schema := fmt.Sprintf("auth_sms_test_%d_%d", os.Getpid(), time.Now().UnixNano())
	if _, err := adminDB.Pool.Exec(ctx, `CREATE SCHEMA `+schema); err != nil {
		adminDB.Close()
		t.Fatalf("create isolated auth test schema: %v", err)
	}
	t.Cleanup(func() {
		cleanupCtx, cleanupCancel := context.WithTimeout(context.Background(), 10*time.Second)
		defer cleanupCancel()
		_, _ = adminDB.Pool.Exec(cleanupCtx, `DROP SCHEMA `+schema+` CASCADE`)
		adminDB.Close()
	})

	poolConfig, err := pgxpool.ParseConfig(url)
	if err != nil {
		t.Fatalf("parse auth test database URL: %v", err)
	}
	poolConfig.ConnConfig.RuntimeParams["search_path"] = schema
	pool, err := pgxpool.NewWithConfig(ctx, poolConfig)
	if err != nil {
		t.Fatalf("create isolated auth test connection pool: %v", err)
	}
	t.Cleanup(pool.Close)
	if err := pool.Ping(ctx); err != nil {
		t.Fatalf("ping isolated auth test database: %v", err)
	}
	if _, err := pool.Exec(ctx, `
		CREATE TABLE sms_login_codes (
			id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
			phone TEXT NOT NULL,
			code_hash TEXT NOT NULL,
			expires_at TIMESTAMPTZ NOT NULL,
			attempts INTEGER NOT NULL DEFAULT 0,
			consumed_at TIMESTAMPTZ,
			created_at TIMESTAMPTZ NOT NULL DEFAULT now()
		)
	`); err != nil {
		t.Fatalf("create isolated SMS code table: %v", err)
	}
	if _, err := pool.Exec(ctx, `
		CREATE TABLE auth_attempts (
			id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
			phone TEXT,
			remote_key TEXT NOT NULL,
			action TEXT NOT NULL,
			succeeded BOOLEAN NOT NULL DEFAULT FALSE,
			created_at TIMESTAMPTZ NOT NULL DEFAULT now()
		)
	`); err != nil {
		t.Fatalf("create isolated auth attempt table: %v", err)
	}
	if _, err := pool.Exec(ctx, `
		CREATE TABLE users (
			id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
			phone TEXT NOT NULL UNIQUE,
			updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
		)
	`); err != nil {
		t.Fatalf("create isolated user table: %v", err)
	}
	if _, err := pool.Exec(ctx, `
		CREATE TABLE project_invites (
			id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
			project_id UUID NOT NULL,
			phone TEXT NOT NULL,
			role TEXT NOT NULL,
			accepted_at TIMESTAMPTZ,
			revoked_at TIMESTAMPTZ,
			expires_at TIMESTAMPTZ NOT NULL,
			created_at TIMESTAMPTZ NOT NULL DEFAULT now()
		)
	`); err != nil {
		t.Fatalf("create isolated project invite table: %v", err)
	}
	return &database.DB{Pool: pool}
}
